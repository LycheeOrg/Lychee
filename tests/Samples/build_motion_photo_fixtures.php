/**
 * Rebuilds the synthetic Google Motion Photo 1.0 fixtures of Feature 098
 * (FX-098-01, FX-098-02, FX-098-04):
 *
 *  - google_motion_photo_v1.jpg        Primary + MotionPhoto
 *  - google_motion_photo_ultrahdr.jpg  Primary + GainMap + MotionPhoto
 *
 * The still is mongolia.jpeg with its XMP packet replaced by a motion photo
 * packet written like a Pixel camera writes it (attributes on
 * `Container:Item`, no `Item:Length` on the primary item). The gain map is
 * the real one of google_motion_photo_pixel.jpg. The video is a one second
 * H.264 test pattern generated by FFmpeg.
 *
 * Usage: php tests/Samples/build_motion_photo_fixtures.php [path/to/ffmpeg]
 */
const SAMPLES_DIR = __DIR__;
const XMP_STD_NAMESPACE = "http://ns.adobe.com/xap/1.0/\x00";

// Layout of google_motion_photo_pixel.jpg, see the Appendix of the spec.
const PIXEL_VIDEO_LENGTH = 3725212;
const PIXEL_GAIN_MAP_LENGTH = 1753;

$ffmpeg = $argv[1] ?? 'ffmpeg';

$still = file_get_contents(SAMPLES_DIR . '/mongolia.jpeg');
$gain_map = read_pixel_gain_map(SAMPLES_DIR . '/google_motion_photo_pixel.jpg');
$video = generate_clip($ffmpeg);

write_fixture('google_motion_photo_v1.jpg', $still, [
	['mime' => 'video/mp4', 'semantic' => 'MotionPhoto', 'bytes' => $video],
]);
write_fixture('google_motion_photo_ultrahdr.jpg', $still, [
	['mime' => 'image/jpeg', 'semantic' => 'GainMap', 'bytes' => $gain_map],
	['mime' => 'video/mp4', 'semantic' => 'MotionPhoto', 'bytes' => $video],
]);

/**
 * @param array<int,array{mime:string,semantic:string,bytes:string}> $secondary_items
 */
function write_fixture(string $name, string $still, array $secondary_items): void
{
	$xmp = motion_photo_xmp($secondary_items);
	$bytes = replace_xmp($still, $xmp) . implode('', array_column($secondary_items, 'bytes'));
	file_put_contents(SAMPLES_DIR . '/' . $name, $bytes);
	echo $name . ': ' . strlen($bytes) . " bytes\n";
}

/**
 * @param array<int,array{mime:string,semantic:string,bytes:string}> $secondary_items
 */
function motion_photo_xmp(array $secondary_items): string
{
	$items = "          <rdf:li rdf:parseType=\"Resource\">\n" .
		"            <Container:Item\n" .
		"              Item:Mime=\"image/jpeg\"\n" .
		"              Item:Semantic=\"Primary\"/>\n" .
		"          </rdf:li>\n";
	foreach ($secondary_items as $item) {
		$items .= "          <rdf:li rdf:parseType=\"Resource\">\n" .
			"            <Container:Item\n" .
			'              Item:Mime="' . $item['mime'] . "\"\n" .
			'              Item:Semantic="' . $item['semantic'] . "\"\n" .
			'              Item:Length="' . strlen($item['bytes']) . "\"\n" .
			"              Item:Padding=\"0\"/>\n" .
			"          </rdf:li>\n";
	}

	return "<x:xmpmeta xmlns:x=\"adobe:ns:meta/\" x:xmptk=\"Lychee motion photo fixture\">\n" .
		"  <rdf:RDF xmlns:rdf=\"http://www.w3.org/1999/02/22-rdf-syntax-ns#\">\n" .
		"    <rdf:Description rdf:about=\"\"\n" .
		"        xmlns:GCamera=\"http://ns.google.com/photos/1.0/camera/\"\n" .
		"        xmlns:Container=\"http://ns.google.com/photos/1.0/container/\"\n" .
		"        xmlns:Item=\"http://ns.google.com/photos/1.0/container/item/\"\n" .
		"      GCamera:MotionPhoto=\"1\"\n" .
		"      GCamera:MotionPhotoVersion=\"1\"\n" .
		"      GCamera:MotionPhotoPresentationTimestampUs=\"500000\">\n" .
		"      <Container:Directory>\n" .
		"        <rdf:Seq>\n" .
		$items .
		"        </rdf:Seq>\n" .
		"      </Container:Directory>\n" .
		"    </rdf:Description>\n" .
		"  </rdf:RDF>\n" .
		"</x:xmpmeta>\n";
}

/**
 * Returns the JPEG with its standard XMP APP1 segment replaced by `$xmp`,
 * or with `$xmp` added after the last APPn segment when there was none.
 */
function replace_xmp(string $jpeg, string $xmp): string
{
	$payload = XMP_STD_NAMESPACE . $xmp;
	$segment = "\xFF\xE1" . pack('n', strlen($payload) + 2) . $payload;

	$head = "\xFF\xD8";
	$offset = 2;
	$inserted = false;
	while (true) {
		$marker = ord($jpeg[$offset + 1]);
		$length = unpack('n', substr($jpeg, $offset + 2, 2))[1];
		$raw = substr($jpeg, $offset, $length + 2);
		$is_app = $marker >= 0xE0 && $marker <= 0xEF;
		$is_xmp = $marker === 0xE1 && str_starts_with(substr($raw, 4), XMP_STD_NAMESPACE);

		if (!$is_app && !$inserted) {
			$head .= $segment;
			$inserted = true;
		}
		$head .= $is_xmp ? '' : $raw;
		if ($marker === 0xDA) {
			break;
		}
		$offset += $length + 2;
	}

	return $head . substr($jpeg, $offset + strlen($raw));
}

function read_pixel_gain_map(string $path): string
{
	$bytes = file_get_contents($path);
	$gain_map = substr($bytes, -(PIXEL_VIDEO_LENGTH + PIXEL_GAIN_MAP_LENGTH), PIXEL_GAIN_MAP_LENGTH);
	if (!str_starts_with($gain_map, "\xFF\xD8") || !str_ends_with($gain_map, "\xFF\xD9")) {
		fwrite(STDERR, "Unexpected layout of $path\n");
		exit(1);
	}

	return $gain_map;
}

function generate_clip(string $ffmpeg): string
{
	$base = tempnam(sys_get_temp_dir(), 'lychee-clip-');
	$target = $base . '.mp4';
	$command = escapeshellarg($ffmpeg) . ' -v error -y' .
		' -f lavfi -i testsrc2=size=320x240:rate=15:duration=1' .
		' -c:v libx264 -preset veryslow -crf 35 -pix_fmt yuv420p -g 15 -bf 0' .
		' -map_metadata -1 -fflags +bitexact -flags:v +bitexact -brand isom ' .
		escapeshellarg($target);
	exec($command, $output, $status);
	if ($status !== 0) {
		fwrite(STDERR, "FFmpeg failed\n");
		exit(1);
	}
	$clip = file_get_contents($target);
	unlink($target);
	unlink($base);

	return $clip;
}
